import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";
import { getSession, isAdminRole } from "@/lib/auth";
import { rateLimit } from "@/lib/rate-limit";
import { GATE_TAP_BUDGET, GATE_TAP_WINDOW_MS } from "@/lib/api/rate-limit-budgets";
import { validateBody } from "@/lib/api/validate";
import { gateActionSchema } from "@/lib/validations/gate";
import { getTodayInTimezone } from "@/lib/attendance/timezone";
import { getGateRoster, listGateCampuses, resolveDefaultGateCampusId } from "@/lib/attendance/gate-summary";
import { reconcileSessions } from "@/lib/sessions/reconcile";

/**
 * Gerbang (gate) mode — drop-off / pick-up at the front door, one tap per
 * child, from any teacher login (no class assignment or piket needed).
 *
 * GET  /api/teacher/gate?campusId=  every ACTIVE-enrolled student on the
 *      campus (default: the caller's campus) with today's arrival / pickup.
 * POST /api/teacher/gate            { studentId, action, relation?, name? }
 *
 * Writes the SAME StudentAttendance row the class session view reads: the
 * row is keyed (studentId, sessionId) on the child's class section's
 * ClassSession for today. Sessions are generated by `reconcileSessions`
 * (never created ad hoc); if today's session is missing the gate runs a
 * reconcile once before giving up.
 *
 * Auth mirrors the session routes: TEACHER or admin, with an employeeId
 * (checkedInBy). Tenant scoping is indirect for sessions
 * (`classSection.tenantId`) and direct for students / campuses.
 */

const TZ = "Asia/Jakarta";

async function authorize() {
  const session = await getSession();
  if (!session?.tenantId) {
    return { error: NextResponse.json({ error: "Unauthorized" }, { status: 401 }) };
  }
  if (session.role !== "TEACHER" && !isAdminRole(session.role)) {
    return { error: NextResponse.json({ error: "Forbidden" }, { status: 403 }) };
  }
  if (!session.employeeId) {
    return { error: NextResponse.json({ error: "Forbidden" }, { status: 403 }) };
  }
  return { session: { ...session, tenantId: session.tenantId, employeeId: session.employeeId } };
}

export async function GET(req: NextRequest) {
  const auth = await authorize();
  if (auth.error) return auth.error;
  const { session } = auth;
  const { tenantId } = session;

  const campuses = await listGateCampuses(tenantId);

  let campusId = new URL(req.url).searchParams.get("campusId");
  if (campusId) {
    if (!campuses.some((c) => c.id === campusId)) {
      return NextResponse.json({ error: "Kampus tidak ditemukan" }, { status: 404 });
    }
  } else {
    campusId = await resolveDefaultGateCampusId(tenantId, session.employeeId, campuses);
  }

  const date = getTodayInTimezone(TZ);
  if (!campusId) {
    return NextResponse.json({ date, campusId: null, campuses, students: [] });
  }

  const { students: unique, byStudent } = await getGateRoster(tenantId, campusId, date);

  return NextResponse.json({
    date,
    campusId,
    campuses,
    students: unique.map((e) => {
      const a = byStudent.get(e.student.id);
      return {
        studentId: e.student.id,
        name: e.student.name,
        nickname: e.student.nickname,
        classSectionId: e.classSection.id,
        className: e.classSection.name,
        status: a?.status ?? null,
        checkInTime: a?.checkInTime?.toISOString() ?? null,
        checkOutTime: a?.checkOutTime?.toISOString() ?? null,
        pickedUpByRelation: a?.pickedUpByRelation ?? null,
        pickedUpByName: a?.pickedUpByName ?? null,
      };
    }),
  });
}

/** Arrival prefers the morning/full-day session; pickup the later one. */
const SLOT_PREFERENCE = {
  arrive: ["FULL_DAY", "MORNING", "AFTERNOON"],
  pickup: ["FULL_DAY", "AFTERNOON", "MORNING"],
} as const;

async function findSessions(classSectionId: string, date: string) {
  return prisma.classSession.findMany({
    where: { classSectionId, date },
    select: { id: true, slot: true, date: true },
  });
}

export async function POST(req: NextRequest) {
  const auth = await authorize();
  if (auth.error) return auth.error;
  const { session } = auth;
  const { tenantId, employeeId } = session;

  // Per user, not per IP — one school Wi-Fi, one shared tablet.
  const { success } = rateLimit(
    `gate:${session.id}`,
    GATE_TAP_BUDGET,
    GATE_TAP_WINDOW_MS,
  );
  if (!success) {
    return NextResponse.json({ error: "Terlalu banyak permintaan" }, { status: 429 });
  }

  const result = await validateBody(gateActionSchema, await req.json());
  if (result.error) return result.error;
  const { studentId, action, campusId, relation, name } = result.data;

  // Student must belong to the tenant and be ACTIVE-enrolled in an ACTIVE
  // class on the (requested) campus.
  const enrollment = await prisma.studentEnrollment.findFirst({
    where: {
      studentId,
      status: "ACTIVE",
      student: { tenantId },
      classSection: {
        tenantId,
        status: "ACTIVE",
        ...(campusId ? { campusId } : {}),
      },
    },
    select: { classSectionId: true },
  });
  if (!enrollment) {
    return NextResponse.json(
      { error: "Siswa tidak ditemukan di kampus ini" },
      { status: 404 },
    );
  }
  const { classSectionId } = enrollment;
  const date = getTodayInTimezone(TZ);

  // Reuse the session this child already has a row on today (so pickup lands
  // beside the arrival); otherwise pick by slot.
  const existing = await prisma.studentAttendance.findFirst({
    where: { studentId, date, sessionId: { not: null }, session: { classSectionId } },
    select: {
      id: true,
      sessionId: true,
      status: true,
      checkInTime: true,
      checkOutTime: true,
      isVoided: true,
    },
    orderBy: { createdAt: "asc" },
  });

  let sessionId = existing?.sessionId ?? null;
  if (!sessionId) {
    const wanted = action === "pickup" || action === "undo_pickup" ? "pickup" : "arrive";
    let sessions = await findSessions(classSectionId, date);
    if (sessions.length === 0) {
      await reconcileSessions(classSectionId);
      sessions = await findSessions(classSectionId, date);
    }
    const chosen = SLOT_PREFERENCE[wanted]
      .map((slot) => sessions.find((s) => s.slot === slot))
      .find(Boolean);
    sessionId = chosen?.id ?? sessions[0]?.id ?? null;
  }
  if (!sessionId) {
    return NextResponse.json(
      { error: "Belum ada sesi kelas hari ini" },
      { status: 409 },
    );
  }

  const where = { studentId_sessionId: { studentId, sessionId } };
  const now = new Date();

  if (action === "undo_arrive") {
    // Only reverses a bare arrival; a row that already has a pickup stays.
    if (existing && existing.status === "PRESENT" && !existing.checkOutTime) {
      await prisma.studentAttendance.delete({ where });
    }
    return NextResponse.json({ ok: true, undone: true });
  }

  if (action === "undo_pickup") {
    if (existing?.checkOutTime) {
      await prisma.studentAttendance.update({
        where,
        data: { checkOutTime: null, pickedUpByRelation: null, pickedUpByName: null },
      });
    }
    return NextResponse.json({ ok: true, undone: true });
  }

  // Idempotent: tapping the same mode again changes nothing.
  if (
    existing &&
    !existing.isVoided &&
    existing.status === "PRESENT" &&
    (action === "arrive" ? existing.checkInTime : existing.checkOutTime)
  ) {
    return NextResponse.json({
      ok: true,
      alreadyDone: true,
      sessionId,
      time: (action === "arrive" ? existing.checkInTime : existing.checkOutTime)!.toISOString(),
    });
  }

  const base = { classSectionId, date, status: "PRESENT", checkedInBy: employeeId, isVoided: false };
  const fields =
    action === "arrive"
      ? { checkInTime: now }
      : {
          checkOutTime: now,
          pickedUpByRelation: relation ?? "PARENT",
          pickedUpByName: name?.trim() || null,
        };

  await prisma.studentAttendance.upsert({
    where,
    create: { studentId, sessionId, ...base, ...fields },
    update: { ...base, ...fields },
  });

  return NextResponse.json({ ok: true, sessionId, time: now.toISOString() });
}
